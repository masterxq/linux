/*
 * A job without the main output does not depend on the format of the main
 * node, and a geometry that passes the check of STREAMON gets a tile layout
 * in each job.
 */
static void mtk_dip_tile_test_no_main(struct kunit *test)
{
	const unsigned int max = MTK_DIP_TILE_MAX * MTK_DIP_TILE_WORDS_MAX;
	const u32 scale = MTK_DIP_PROFILE_SCALE;
	struct v4l2_pix_format_mplane in = {
		.width = 4624, .height = 3472,
		.pixelformat = V4L2_PIX_FMT_MTISP_SBGGR10,
		.plane_fmt[0].bytesperline = 5780,
	};
	struct v4l2_pix_format_mplane out = {
		.width = 2304, .height = 1728,
		.plane_fmt[0].bytesperline = 2304,
	};
	struct v4l2_pix_format_mplane sc = {
		.width = 1920, .height = 1080,
		.plane_fmt[0].bytesperline = 3840,
	};
	struct v4l2_rect crop = { 0, 436, 4624, 2600 };
	struct mtk_dip_tile_layout *l, *l2;
	struct mtk_dip_tile_geom g, g2;
	struct mtk_dip_frame_cfg f;
	u32 *tdr, *tdr2;

	l = kunit_kzalloc(test, sizeof(*l), GFP_KERNEL);
	l2 = kunit_kzalloc(test, sizeof(*l2), GFP_KERNEL);
	tdr = kunit_kcalloc(test, max, sizeof(*tdr), GFP_KERNEL);
	tdr2 = kunit_kcalloc(test, max, sizeof(*tdr2), GFP_KERNEL);
	KUNIT_ASSERT_NOT_NULL(test, l);
	KUNIT_ASSERT_NOT_NULL(test, l2);
	KUNIT_ASSERT_NOT_NULL(test, tdr);
	KUNIT_ASSERT_NOT_NULL(test, tdr2);
	mtk_dip_frame_cfg_init(&f, in.width, in.height);

	/* the main node holds 2304x1728, only the scaled node streams */
	KUNIT_ASSERT_EQ(test, mtk_dip_job_geometry(&in, &crop, NULL, &sc, NULL, NULL, &g), 0);
	KUNIT_EXPECT_EQ(test, g.profile, scale | MTK_DIP_PROFILE_NO_MAIN);
	KUNIT_EXPECT_EQ(test, g.bpp, 10);
	KUNIT_EXPECT_EQ(test, g.out_stride, 0);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_check(&g), 0);
	KUNIT_ASSERT_EQ(test, mtk_dip_tile_compute(&g, &f, l, tdr, max), 0);
	KUNIT_EXPECT_EQ(test, l->need_y, 0);
	KUNIT_EXPECT_EQ(test, l->need_s, 3840 * 1080);
	/* a line size of the main output, smaller than the area, changes nothing */
	g2 = g;
	g2.out_stride = out.plane_fmt[0].bytesperline;
	KUNIT_ASSERT_EQ(test, mtk_dip_tile_compute(&g2, &f, l2, tdr2, max), 0);
	KUNIT_ASSERT_EQ(test, l2->tdr_bytes, l->tdr_bytes);
	KUNIT_EXPECT_MEMEQ(test, tdr2, tdr, l->tdr_bytes);

	/* with the main output, its format has the size of the area */
	KUNIT_EXPECT_EQ(test, mtk_dip_job_geometry(&in, &crop, &out, &sc, NULL, NULL, &g),
			-EPIPE);
	out.width = 4624;
	out.height = 2600;
	out.plane_fmt[0].bytesperline = 4624;
	KUNIT_ASSERT_EQ(test, mtk_dip_job_geometry(&in, &crop, &out, &sc, NULL, NULL, &g), 0);
	KUNIT_EXPECT_EQ(test, g.profile, scale);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_check(&g), 0);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_compute(&g, &f, l, tdr, max), 0);
	g.out_stride = 4608;
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_check(&g), -EINVAL);

	/* scaled output larger than half the area: rejected before any job */
	crop = (struct v4l2_rect){ 1156, 868, 2312, 1736 };
	KUNIT_ASSERT_EQ(test, mtk_dip_job_geometry(&in, &crop, NULL, &sc, NULL, NULL, &g), 0);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_check(&g), -EINVAL);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_compute(&g, &f, l, tdr, max), -EINVAL);

	/*
	 * A width only the module set with edge enhancement cannot serve: a
	 * job without it would run, the check rejects it as the parameters
	 * may switch the edge enhancement on
	 */
	crop = (struct v4l2_rect){ 0, 0, 700, 480 };
	out.width = 700;
	out.height = 480;
	out.plane_fmt[0].bytesperline = 704;
	KUNIT_ASSERT_EQ(test, mtk_dip_job_geometry(&in, &crop, &out, NULL, NULL, NULL, &g), 0);
	KUNIT_EXPECT_EQ(test, g.profile, 0);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_compute(&g, &f, l, tdr, max), 0);
	KUNIT_EXPECT_EQ(test, mtk_dip_tile_check(&g), -ERANGE);
}

