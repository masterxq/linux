#define OV64B40_LANES			4
#define OV64B40_BITS_PER_SAMPLE		10
#define OV64B40_LINK_FREQ		849600000ULL	/* 1699.2 Mbit/s per lane */
#define OV64B40_PIXEL_RATE		679680000ULL
#define OV64B40_MCLK_FREQ		24000000

#define OV64B40_REG_CHIP_ID		CCI_REG16(0x300b)
#define OV64B40_CHIP_ID			0x6442

#define OV64B40_REG_MODE_SELECT		CCI_REG8(0x0100)
#define OV64B40_MODE_STANDBY		0x00
#define OV64B40_MODE_STREAMING		0x01
#define OV64B40_REG_SOFTWARE_RESET	CCI_REG8(0x0103)

/*
 * Group hold: bits 3:0 the group, bits 7:4 start (0x0), end (0x1) and launch
 * (0xa) of the group. A launched group applies at the next frame boundary.
 */
#define OV64B40_REG_GROUP_HOLD		CCI_REG8(0x3208)
#define OV64B40_GROUP_START		0x00
#define OV64B40_GROUP_END		0x10
#define OV64B40_GROUP_LAUNCH		0xa0

/*
 * The vendor driver writes every register of the exposure, gain and frame
 * length as a single byte; so does this driver.
 */

/* exposure in lines (bits 23:16, 15:8, 7:0), the vendor driver keeps it even */
#define OV64B40_REG_EXPOSURE_H		CCI_REG8(0x3500)
#define OV64B40_REG_EXPOSURE_M		CCI_REG8(0x3501)
#define OV64B40_REG_EXPOSURE_L		CCI_REG8(0x3502)
#define OV64B40_EXPOSURE_MIN		16
#define OV64B40_EXPOSURE_MARGIN		31
#define OV64B40_EXPOSURE_STEP		2

/* analogue gain, 0x100 = 1x, bits 14:8 and 7:1, vendor steps of 4 */
#define OV64B40_REG_ANALOGUE_GAIN_H	CCI_REG8(0x3508)
#define OV64B40_REG_ANALOGUE_GAIN_L	CCI_REG8(0x3509)
#define OV64B40_GAIN_MIN		0x100
#define OV64B40_GAIN_MAX		0xf80	/* 15.5x */
#define OV64B40_GAIN_STEP		4

/* frame length: bits 23:16 in 0x3840, bits 15:0 in 0x380e/0x380f, even */
#define OV64B40_REG_VTS_HIGH		CCI_REG8(0x3840)
#define OV64B40_REG_VTS_MID		CCI_REG8(0x380e)
#define OV64B40_REG_VTS_LOW		CCI_REG8(0x380f)
#define OV64B40_VTS_MAX			0xffffe8

/*
 * Test pattern: bit 0 enable, bits 5:4 pattern. The vendor driver writes
 * 0x5081, which reads back 0 on the sensor while streaming and leaves the
 * image unchanged; the init sequence clears 0x50c1, the test pattern
 * register of the OV64A40 with the same bit layout.
 */
#define OV64B40_REG_TEST_PATTERN	CCI_REG8(0x50c1)

/*
 * Pixel array as addressed by the vendor windows (0x3800..0x3807 cover
 * 9280x6976), the active area is the 9248x6944 full resolution output.
 */
#define OV64B40_NATIVE_WIDTH		9280
#define OV64B40_NATIVE_HEIGHT		6976
#define OV64B40_ACTIVE_LEFT		16
#define OV64B40_ACTIVE_TOP		16
#define OV64B40_ACTIVE_WIDTH		9248
#define OV64B40_ACTIVE_HEIGHT		6944

/*
 * A line is HTS periods of the 115.2 MHz timing clock, in periods of the
 * 679.68 MHz pixel rate HTS * 5.9: 936 -> 5522 (8.124 us), 640 -> 3776
 * (5.556 us).
 */
#define OV64B40_LINE_LENGTH_4624	5522
#define OV64B40_LINE_LENGTH_2304	3776

/*
 * Phase detection pixels: in the modes with phase_detect set the sensor
 * sends them on virtual channel 1 as RAW10, the image on virtual channel 0.
 * Layout from the vendor sensor driver (GPL) for the 4624x3472 mode: 16x16
 * blocks from (40, 16), 284 x 215 of them, each with 8 pairs of left and
 * right phase detection pixels in 4 rows of 4 samples. The virtual channel
 * carries 1136 x 860 samples a frame, 4 samples per block and line.
 */
#define OV64B40_PD_VC			1

struct ov64b40_mode {
	u32 width;
	u32 height;
	u32 line_length;	/* in periods of the pixel rate */
	u32 vts;
	bool phase_detect;
	struct v4l2_rect crop;
	const struct cci_reg_sequence *regs;
	unsigned int num_regs;
};

