/*
 * OmniVision OV64B40 image sensor driver (64 MP quad Bayer, 4-lane MIPI CSI-2)
 *
 * Two modes, SBGGR10, 4 lanes at 1699.2 Mbit/s, 30 fps, both with the full
 * field of view:
 * - 4624x3472, 2x2 binned (vendor preview_setting),
 * - 2304x1728, binned and subsampled by four (vendor hs_video_setting, a
 *   1920x1080 centre crop at 120 fps there, with the window of the full
 *   array and a longer line here).
 * The register sequences (sensor_init and the mode settings, order and
 * repeated writes kept), the power sequence and the exposure, frame length,
 * gain and test pattern registers come from the vendor kernel of the
 * Motorola Moto G60s (GPL-2.0).
 *
 * Timing: the modes run at a 115.2 MHz timing clock, 4624x3472 with HTS 936
 * and VTS 4102 (30.004 fps), 2304x1728 with HTS 640 and VTS 6000 (30.000
 * fps). The CSI-2 transmitter runs at a pixel rate of 679.68 MHz in both,
 * 679.68 MHz * 10 bit / 4 lanes = 1699.2 Mbit/s per lane, 849.6 MHz DDR link
 * frequency.
 */

